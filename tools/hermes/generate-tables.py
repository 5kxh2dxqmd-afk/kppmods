#!/usr/bin/env python3
"""Generate native discovery metadata from the hermes-dec submodule (build tool only)."""

import ctypes
import json
import sys
from pathlib import Path
from types import SimpleNamespace

from signatures import REQUIRED, SIGNATURES

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / "vendor/hermes-dec/src"))
from hermes_dec.parsers.hbc_bytecode_parser import get_parser  # noqa: E402
from hermes_dec.parsers.hbc_file_parser import HBCReader  # noqa: E402

out = ["// Generated by tools/hermes/generate-tables.py from hermes-dec (AGPL-3.0)."]


def field(cls, name):
    item = getattr(cls, name)
    entry = next(f for f in cls._fields_ if f[0] == name)
    bits = entry[2] if len(entry) == 3 else ctypes.sizeof(entry[1]) * 8
    shift = getattr(item, "bit_offset", item.size & 65535) if len(entry) == 3 else 0
    return "{%d,%d,%d}" % (item.offset, shift, bits)


versions = []
op_tables = {}
for version in range(72, 100):
    try:
        parser = get_parser(version)
    except (ValueError, NotImplementedError):
        continue
    reader = HBCReader()
    reader.header = SimpleNamespace(version=version)
    small, large = (
        reader.get_small_func_header_reader(),
        reader.get_large_func_header_reader(),
    )
    header = reader.get_header_reader(version)
    ops = []
    for inst in parser._instructions:
        action = {
            "CreateClosure": "CreateClosure",
            "CreateClosureLongIndex": "CreateClosure",
            "LoadConstUInt8": "LoadConstant",
            "LoadConstInt": "LoadConstant",
            "LoadConstZero": "LoadZero",
            "Mov": "Move",
            "MovLong": "Move",
            "Call4": "Call",
        }.get(inst.name, "None")
        operands = [
            "{%d,Meaning::%s}"
            % (
                ctypes.sizeof(o.operand_type.c_type),
                {2: "Function", 3: "String"}.get(
                    o.operand_meaning.value if o.operand_meaning else 0, "Other"
                ),
            )
            for o in inst.operands
        ]
        ops.append(
            "{%d,%d,Action::%s,%d,{%s}}"
            % (
                inst.binary_size,
                len(operands),
                action,
                inst.name.startswith("PutById"),
                ",".join(operands),
            )
        )
    key = tuple(ops)
    if key not in op_tables:
        op_tables[key] = version
        out.append(
            "static constexpr Opcode ops%d[] = {\n%s\n};" % (version, ",\n".join(ops))
        )
    op_version = op_tables[key]
    sf = ",".join(
        field(small, n)
        for n in (
            "offset",
            "bytecodeSizeInBytes",
            "overflowed",
            "infoOffset" if version < 97 else "functionName",
        )
    )
    lf = ",".join(field(large, n) for n in ("offset", "bytecodeSizeInBytes"))
    versions.append(
        "{%d,%d,%d,%d,{%s},{%s},ops%d,sizeof(ops%d)/sizeof(Opcode)}"
        % (
            version,
            (ctypes.sizeof(header) + 31) & ~31,
            ctypes.sizeof(small),
            24 if version >= 98 else 16,
            sf,
            lf,
            op_version,
            op_version,
        )
    )
out.append("static constexpr Format formats[] = {\n" + ",\n".join(versions) + "\n};")
signatures = SIGNATURES
wanted = sorted(set().union(*signatures.values()) | {"__d"})
out.append(
    "static constexpr const char *needles[] = {"
    + ",".join(map(json.dumps, wanted))
    + "};"
)
for name, strings in signatures.items():
    out.append(
        "static constexpr unsigned signature_%s[] = {%s};"
        % (name, ",".join(str(wanted.index(s)) for s in sorted(strings)))
    )
out.append(
    "static const Signature signatures[] = {"
    + ",".join(
        '{"%s",signature_%s,sizeof(signature_%s)/sizeof(unsigned),%s}'
        % (n, n, n, str(n in REQUIRED).lower())
        for n in signatures
    )
    + "};"
)
Path(
    sys.argv[1] if len(sys.argv) > 1 else root / "src/runtime/hermes/tables.inc"
).write_text("\n".join(out) + "\n")
